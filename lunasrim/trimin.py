"""Reading and writing of TRIM.IN files (SRIM-2013 format)."""
import re
import struct


def f32(x):
    """round to IEEE single precision (VB ``Single``)"""
    return struct.unpack('<f', struct.pack('<f', float(x)))[0]


def _num(tok):
    """VB ``Input #`` into a Variant: integers stay integers"""
    tok = tok.strip()
    try:
        return int(tok)
    except ValueError:
        return float(tok)


class _Reader(object):
    """Minimal emulation of Visual Basic ``Line Input #`` / ``Input #``."""

    def __init__(self, text):
        self.t = text.replace('\r\n', '\n').replace('\r', '\n')
        self.p = 0

    def line(self):
        i = self.t.find('\n', self.p)
        if i < 0:
            s = self.t[self.p:]
            self.p = len(self.t)
        else:
            s = self.t[self.p:i]
            self.p = i + 1
        return s

    def _skipdelim(self):
        t, n = self.t, len(self.t)
        while self.p < n and t[self.p] in ' \t':
            self.p += 1
        if self.p < n and t[self.p] == ',':
            self.p += 1
        elif self.p < n and t[self.p] == '\n':
            self.p += 1

    def token(self, string=False):
        t, n = self.t, len(self.t)
        while self.p < n and t[self.p] in ' \t\n':
            self.p += 1
        if self.p < n and t[self.p] == '"':
            j = t.index('"', self.p + 1)
            s = t[self.p + 1:j]
            self.p = j + 1
            self._skipdelim()
            return s
        j = self.p
        stops = ',\n' if string else ' \t,\n'
        while j < n and t[j] not in stops:
            j += 1
        s = t[self.p:j]
        self.p = j
        self._skipdelim()
        return s.strip() if string else s

    def num(self):
        return _num(self.token())


class TrimInputElement(object):
    def __init__(self, symbol, z, mass):
        self.symbol = symbol
        self.z = z
        self.mass = mass


class TrimInputLayer(object):
    def __init__(self, name, width, density, stoich):
        self.name = name
        self.width = width
        self.density = density
        self.stoich = stoich      # list over all target elements
        self.phase = 0
        self.bragg = 1.0


class TrimInput(object):
    """Content of a TRIM.IN file."""

    def __init__(self):
        self.title = 'TRIM.IN generated by lunasrim'
        self.ion_z = 1
        self.ion_mass = 1.008
        self.energy = 100.0          # keV
        self.angle = 0.0             # degrees
        self.number_ions = 100
        self.bragg_ion = 1.0
        self.autosave = 0
        self.cascade = 1             # 1 = Kinchin-Pease, 2 = full cascade, 3 = sputtering ...
        self.seed1 = 0
        self.seed2 = 0
        self.reminders = 0
        self.file_ranges = 0
        self.file_backscatt = 0
        self.file_transmit = 0
        self.file_sputtered = 0
        self.file_collisions = 0
        self.file_exyz = 0
        self.target_name = 'target'
        self.plot_type = 5
        self.xmin = 0.0
        self.xmax = 0.0
        self.elements = []
        self.layers = []
        self.ed = []
        self.lattice = []
        self.surface = []
        self.stopping_version = 0

    # ------------------------------------------------------------------ reading
    @classmethod
    def read(cls, path):
        with open(path, 'rb') as fh:
            return cls.parse(fh.read().decode('latin-1'))

    @classmethod
    def parse(cls, text):
        r = _Reader(text)
        ti = cls()
        ti.title = r.line()
        r.line()
        ti.ion_z = int(r.num())
        ti.ion_mass = f32(r.num())
        ti.energy = r.num()
        ti.angle = r.num()
        ti.number_ions = r.num()
        ti.bragg_ion = r.num()
        ti.autosave = int(r.num())
        r.line()
        ti.cascade = int(r.num())
        ti.seed1 = int(r.num())
        ti.seed2 = int(r.num())
        r.line()
        ti.file_ranges = int(r.num())
        ti.file_backscatt = int(r.num())
        ti.file_transmit = int(r.num())
        ti.file_sputtered = int(r.num())
        ti.file_collisions = int(r.num())
        ti.file_exyz = r.num()
        r.line()
        ti.target_name = r.token(string=True)
        nel = int(r.num())
        nlay = int(r.num())
        r.line()
        ti.plot_type = int(r.num())
        ti.xmin = r.num()
        ti.xmax = r.num()
        r.line()
        for i in range(nel):
            line = r.line()
            m = re.match(r'\s*Atom\s+\d+\s*=\s*(\S*)\s*=\s*([-+0-9.eE]+)\s+([-+0-9.eE]+)', line)
            if m is None:
                toks = line.split()
                sym, z, mass = toks[3], toks[5], toks[6]
            else:
                sym, z, mass = m.group(1), m.group(2), m.group(3)
            ti.elements.append(TrimInputElement(sym, int(float(z)), _num(mass)))
        r.line()
        r.line()
        for j in range(nlay):
            r.num()                       # layer number
            name = r.token(string=False)
            width = r.num()
            density = f32(r.num())
            stoich = [f32(r.num()) for i in range(nel)]
            ti.layers.append(TrimInputLayer(name, width, density, stoich))
        r.line()
        for lay in ti.layers:
            lay.phase = int(r.num())
        r.line()
        for lay in ti.layers:
            lay.bragg = r.num()
        r.line()
        ti.ed = [r.num() for i in range(nel)]
        r.line()
        ti.lattice = [r.num() for i in range(nel)]
        r.line()
        ti.surface = [r.num() for i in range(nel)]
        r.line()
        try:
            ti.stopping_version = int(r.num())
        except (ValueError, IndexError):
            ti.stopping_version = 0
        return ti

    # ------------------------------------------------------------------ writing
    def to_string(self):
        nl = '\r\n'
        out = []
        out.append(self.title)
        out.append('Ion: Z, Mass [amu], Energy [keV], Angle [degrees], Number Ions, Bragg Corr, AutoSave Number')
        out.append('%d %s %s %s %d %s %d' % (self.ion_z, self.ion_mass, self.energy, self.angle,
                                            self.number_ions, self.bragg_ion, self.autosave))
        out.append('Cascades(1=Kitchn-Peese, 2=Full-Cascade, 3=Sputtering, 4-5=Ions;6-7=Neutrons), '
                   'Random Number Seed, Reminders')
        out.append('%d %d %d' % (self.cascade, self.seed1, self.seed2))
        out.append('Diskfiles (0=no,1=yes): RANGES.txt, BACKSCATT.txt, TRANSMIT.txt, Sputtered, '
                   'COLLISIONS.txt(0=no, 1=Ion, 2=Ion+Recoils), Special EXYZ.txt file')
        out.append('%d %d %d %d %d %s' % (self.file_ranges, self.file_backscatt, self.file_transmit,
                                         self.file_sputtered, self.file_collisions, self.file_exyz))
        out.append('Target material : Number of Elements, Number of Layers')
        out.append('"%s" %d %d' % (self.target_name, len(self.elements), len(self.layers)))
        out.append('PlotType (0-5); Plot Depths: Xmin, Xmax(Ang.) [=0 0 for Viewing Full Target]')
        out.append('%d %s %s' % (self.plot_type, self.xmin, self.xmax))
        out.append('Target Elements:    Z   Mass [amu]')
        for i, e in enumerate(self.elements):
            out.append('Atom %d = %s =     %d %s' % (i + 1, e.symbol, e.z, e.mass))
        out.append('Layer    Layer Name   Width Density  ' + ' '.join('%s(%d)' % (e.symbol, e.z) for e in self.elements))
        out.append('Number   Description  (Ang) (g/cm^3)' + ' '.join('Stoich' for e in self.elements))
        for j, l in enumerate(self.layers):
            out.append('%d "%s" %s %s %s' % (j + 1, l.name, l.width, l.density,
                                             ' '.join('%s' % s for s in l.stoich)))
        out.append('0  Target layer phases (0=Solid, 1=Gas)')
        out.append(' '.join('%d' % l.phase for l in self.layers))
        out.append('Target Compound Corrections (Bragg)')
        out.append(' ' + ' '.join('%s' % l.bragg for l in self.layers))
        out.append('Individual target atom displacement energies (eV)')
        out.append(' ' + ' '.join('%s' % x for x in self.ed))
        out.append('Individual target atom lattice binding energies (eV)')
        out.append(' ' + ' '.join('%s' % x for x in self.lattice))
        out.append('Individual target atom surface binding energies (eV)')
        out.append(' ' + ' '.join('%s' % x for x in self.surface))
        out.append('Stopping Power Version (1=2011, 0=2011)')
        out.append('%d' % self.stopping_version)
        return nl.join(out) + nl

    def write(self, path):
        with open(path, 'wb') as fh:
            fh.write(self.to_string().encode('latin-1'))
